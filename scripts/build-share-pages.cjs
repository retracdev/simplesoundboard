/*
 * Generates the pages that need their own link preview, from the catalog in js/sounds.js:
 *
 *   sound/<id>.html  one per sound, served at /sound/<id> by GitHub Pages
 *   404.html         the same page without a sound; it reads one from the address instead,
 *                    so a brand-new sound or a link using the sound's name still works
 *   leaderboard.html /leaderboard, with the leaderboard's card, which forwards to /#leaderboard
 *
 * Run `npm run build:share` after adding, renaming or removing a sound. Pages for sounds that
 * no longer exist are removed. The social card images come from render-social-cards.cjs.
 */
'use strict';

const fs = require('fs');
const path = require('path');
const vm = require('vm');

const ROOT = path.resolve(__dirname, '..');
const SITE = 'https://soundboard.retrac.space';
const NOTE = 'Generated by scripts/build-share-pages.cjs from js/sounds.js. Do not edit by hand.';

function loadCatalog() {
  const sandbox = { window: {} };
  vm.runInNewContext(fs.readFileSync(path.join(ROOT, 'js/sounds.js'), 'utf8'), sandbox);
  return sandbox.window.SOUND_CATALOG;
}

function escapeHtml(text) {
  return String(text)
    .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;').replace(/'/g, '&#39;');
}

function fill(template, values) {
  return template.replace(/\{\{([A-Z_]+)\}\}/g, (match, key) => {
    if (!(key in values)) throw new Error('No value for ' + match);
    return values[key];
  });
}

function cardImage(name) {
  return SITE + '/assets/social/' + name + '.jpg';
}

function build() {
  const { categories, sounds } = loadCatalog();
  const template = fs.readFileSync(path.join(ROOT, 'scripts/templates/share-page.html'), 'utf8');
  const categoryById = new Map(categories.map((category) => [category.id, category]));
  const count = sounds.length;
  const outDir = path.join(ROOT, 'sound');
  fs.mkdirSync(outDir, { recursive: true });

  const written = new Set();
  sounds.forEach((sound) => {
    if (!/^[a-z0-9-]+$/.test(sound.id)) throw new Error('Sound id is not URL-safe: ' + sound.id);
    const category = categoryById.get(sound.category);
    const description = 'Tap to play “' + sound.name + '” on Simple Soundboard, then explore '
      + (count - 1) + ' more sound effects. Free, no ads.';
    const html = fill(template, {
      GENERATED_NOTE: NOTE,
      TITLE: escapeHtml(sound.name + ' · Simple Soundboard'),
      OG_TITLE: escapeHtml('▶ ' + sound.name),
      DESCRIPTION: escapeHtml(description),
      THEME: category.color,
      CANONICAL: '  <link rel="canonical" href="' + SITE + '/sound/' + sound.id + '">\n',
      URL: SITE + '/sound/' + sound.id,
      IMAGE: cardImage('sounds/' + sound.id),
      IMAGE_ALT: escapeHtml('A big ' + category.label + ' play button for “' + sound.name + '” on Simple Soundboard'),
      SOUND_ID: sound.id,
      HEADING: escapeHtml(sound.name),
      COUNT: String(count),
    });
    const file = sound.id + '.html';
    fs.writeFileSync(path.join(outDir, file), html);
    written.add(file);
  });

  // Drop pages for sounds that were removed or renamed.
  fs.readdirSync(outDir).forEach((file) => {
    if (file.endsWith('.html') && !written.has(file)) fs.unlinkSync(path.join(outDir, file));
  });

  fs.writeFileSync(path.join(ROOT, '404.html'), fill(template, {
    GENERATED_NOTE: NOTE,
    TITLE: 'Simple Soundboard · retrac.space',
    OG_TITLE: 'Simple Soundboard',
    DESCRIPTION: escapeHtml(count + ' fun sound effects without the bloat. Free, no ads. Part of the retrac.space collection.'),
    THEME: '#07060d',
    CANONICAL: '',
    URL: SITE + '/',
    IMAGE: cardImage('home'),
    IMAGE_ALT: 'Simple Soundboard: fun sound effects without the bloat',
    SOUND_ID: '',
    HEADING: 'Simple Soundboard',
    COUNT: String(count),
  }));

  fs.writeFileSync(path.join(ROOT, 'leaderboard.html'), leaderboardPage(count));
  console.log('Wrote ' + written.size + ' sound pages, 404.html and leaderboard.html.');
}

function leaderboardPage(count) {
  const description = 'Which of ' + count + ' sound effects gets played the most? Every play from everyone, counted live on Simple Soundboard.';
  return `<!doctype html>
<!-- ${NOTE} -->
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>Sound Leaderboard · Simple Soundboard</title>
  <meta name="description" content="${escapeHtml(description)}">
  <meta name="theme-color" content="#ffc93c">
  <link rel="canonical" href="${SITE}/leaderboard">
  <meta property="og:site_name" content="Simple Soundboard">
  <meta property="og:type" content="website">
  <meta property="og:title" content="🏆 Sound Leaderboard">
  <meta property="og:description" content="${escapeHtml(description)}">
  <meta property="og:url" content="${SITE}/leaderboard">
  <meta property="og:image" content="${cardImage('leaderboard')}">
  <meta property="og:image:type" content="image/jpeg">
  <meta property="og:image:width" content="1200">
  <meta property="og:image:height" content="630">
  <meta property="og:image:alt" content="The Simple Soundboard Sound Leaderboard podium">
  <meta name="twitter:card" content="summary_large_image">
  <meta name="twitter:title" content="🏆 Sound Leaderboard">
  <meta name="twitter:description" content="${escapeHtml(description)}">
  <meta name="twitter:image" content="${cardImage('leaderboard')}">
  <meta name="twitter:image:alt" content="The Simple Soundboard Sound Leaderboard podium">
  <link rel="icon" href="/assets/favicon.svg" type="image/svg+xml">
  <style>body{margin:0;min-height:100vh;display:grid;place-items:center;background:#07060d;color:#8b86a3;font:16px system-ui,sans-serif}a{color:#f3f0ff}</style>
  <script>window.location.replace('/' + window.location.search + '#leaderboard');</script>
</head>
<body>
  <p>Opening the <a href="/#leaderboard">Sound Leaderboard</a>…</p>
</body>
</html>
`;
}

build();
